-- OAuth connect redesign (audit B-04). The provider callback (verify_jwt = false, reached by
-- whichever browser finishes consent) no longer activates a payroll connection. It exchanges the
-- code, stores the ENCRYPTED tokens here under a fresh random completion nonce, and redirects
-- that nonce to the app deep link. Only the authenticated app session that started the flow
-- (auth.uid() = user_id) can redeem the nonce at POST /<provider>-oauth/complete, which then
-- moves the tokens into payroll_connections. A consent link forwarded to a victim merchant
-- therefore produces a pending row whose nonce is only ever shown to the victim's browser, and
-- the attacker's session can never redeem it.
--
--   id           completion nonce: generated by the callback, shown only to the browser that
--                finished consent. Never derived from the signed `state` the initiator holds.
--   state_nonce  the nonce inside the signed `state`; UNIQUE, so one state can be redeemed at
--                the callback exactly once (replaying a state fails the insert).
--
-- Every read and write goes through the {provider}-oauth Edge Functions with the service role.
-- There is deliberately NO policy and NO grant for anon/authenticated.
create table public.oauth_pending_connections (
  id uuid primary key default gen_random_uuid(),
  state_nonce uuid not null unique,
  user_id uuid not null references auth.users (id) on delete cascade,
  venue_id uuid not null references public.venues (id) on delete cascade,
  organization_id uuid not null references public.organizations (id) on delete cascade,
  provider text not null check (provider in ('square', 'quickbooks', 'gusto')),
  external_account_id text,
  -- Same shape as payroll_connections; ciphertext is bound to venue_id:provider via AES-GCM
  -- additional data, so it can be moved to payroll_connections unchanged but not to another venue.
  encrypted_access_token text not null,
  encrypted_refresh_token text,
  token_expires_at timestamptz,
  created_at timestamptz not null default now(),
  expires_at timestamptz not null default now() + interval '10 minutes',
  consumed_at timestamptz
);

create index oauth_pending_connections_user_id_idx on public.oauth_pending_connections (user_id);
create index oauth_pending_connections_venue_id_idx on public.oauth_pending_connections (venue_id);
-- Supports the cleanup below (and the opportunistic delete in the Edge Functions).
create index oauth_pending_connections_created_at_idx on public.oauth_pending_connections (created_at);

alter table public.oauth_pending_connections enable row level security;
alter table public.oauth_pending_connections force row level security;

-- No policies: with RLS forced, no client role can see or write a row.
revoke all on public.oauth_pending_connections from public, anon, authenticated;
grant select, insert, update, delete on public.oauth_pending_connections to service_role;

-- Rows are useless after their 10 minute window. The Edge Functions revoke the provider grant of
-- any abandoned row and delete it on the next callback (after 15 minutes); this job is only a
-- backstop for quiet periods and runs a day later, so the revoke normally happens first.
-- SECURITY INVOKER on purpose: it runs as whoever calls it (pg_cron's job owner).
create or replace function app_hidden.cleanup_oauth_pending_connections()
returns bigint
language plpgsql
set search_path = ''
as $$
declare
  v_deleted bigint;
begin
  delete from public.oauth_pending_connections where created_at < now() - interval '24 hours';
  get diagnostics v_deleted = row_count;
  return v_deleted;
end;
$$;

revoke all on function app_hidden.cleanup_oauth_pending_connections() from public, anon, authenticated;

do $$
begin
  if exists (select 1 from pg_extension where extname = 'pg_cron') then
    if exists (select 1 from cron.job where jobname = 'oauth-pending-cleanup') then
      perform cron.unschedule('oauth-pending-cleanup');
    end if;
    perform cron.schedule(
      'oauth-pending-cleanup',
      '*/30 * * * *',
      'select app_hidden.cleanup_oauth_pending_connections();'
    );
  end if;
exception when others then
  null;
end;
$$;
